/// Is `word` a reserved word (case-insensitive)?
pub fn is_reserved(word: &str) -> bool {
    RESERVED.iter().any(|k| k.eq_ignore_ascii_case(word))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_upper_case_and_reserved_are_keywords() {
        for k in RESERVED {
            assert_eq!(*k, k.to_ascii_uppercase());
        }
        for k in KEYWORDS {
            assert_eq!(*k, k.to_ascii_uppercase());
        }
        for f in FUNCTIONS {
            assert_eq!(*f, f.to_ascii_lowercase());
        }
        assert!(is_reserved("select") && is_reserved("Key") && is_reserved("RETURNING"));
        assert!(!is_reserved("name") && !is_reserved("status"));
    }
}
